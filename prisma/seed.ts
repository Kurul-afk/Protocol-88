const questions: SeedQuestion[] = rawQuestions.map((q, idx) => ({
  order: idx + 1,
  text: q.text,
  image: `/images/${idx + 1}.jpg`,
  options: q.options.map(([text, weight], optIdx) => ({
    text,
    weight,
    order: optIdx,
  })),
}));

async function main() {
  for (const q of questions) {
    await prisma.question.create({
      data: {
        order: q.order,
        text: q.text,
        image: q.image,
        options: {
          create: q.options,
        },
      },
    });
  }
  console.log(`Засеяно вопросов: ${questions.length}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
